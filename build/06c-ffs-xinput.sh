#!/bin/bash
# Wired controller mode: build "usb_f_fs_xinput.ko", a renamed copy of the kernel's FunctionFS
# (drivers/usb/gadget/function/f_fs.c) that also accepts class-specific descriptors of any length
# on vendor-specific interfaces. The wired Xbox 360 controller interface carries such a descriptor
# (type 0x21, 17 bytes, describing its endpoints); stock FunctionFS only knows 0x21 as the 9-byte
# HID descriptor and rejects it, and without it Windows' Xbox driver loads but never talks to the
# device. See docs/bt-controller.md (wired mode).
#
# Needs the ROCKNIX kernel tree built by 06b-cedrus.sh (same tree, so symbol versions match).
# The copy registers as filesystem "functionfs_xinput" and USB function "ffsxi", so it sits next
# to the built-in FunctionFS; its three EXPORT_SYMBOLs are dropped (they would clash).
set -euo pipefail
source "$(dirname "$0")/config.sh"
source "$(dirname "$0")/lib/chroot.sh"
trap chroot_umount EXIT
assert_rootfs

K="$WORK/kernel"
T="$K/linux-$LINUX_VERSION-rocknix-$ROCKNIX_VERSION"
export ARCH=arm64 CROSS_COMPILE="$K/gcc15/bin/aarch64-none-linux-gnu-"
[ -f "$T/Module.symvers" ] || die "kernel tree $T not built: run 06b-cedrus.sh first"

M="$K/ffs-xinput"
mkdir -p "$M"
python3 - "$T/drivers/usb/gadget/function/f_fs.c" "$M/f_fs_xinput.c" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()
def sub(pattern, repl, count, flags=0):
    global s
    r = repl if callable(repl) else (lambda m, t=repl: m.expand(t))
    s, n = re.subn(pattern, r, s, flags=flags)
    if n != count:
        sys.exit(f"f_fs.c changed upstream: {pattern!r} matched {n} times, expected {count}")
sub(r'"functionfs"', '"functionfs_xinput"', 3)
sub(r'^EXPORT_SYMBOL_GPL\(\w+\);\n', '', 3, re.M)
sub(r'DECLARE_USB_FUNCTION_INIT\(ffs, ', 'DECLARE_USB_FUNCTION_INIT(ffsxi, ', 1)
sub(r'MODULE_DESCRIPTION\("[^"]*"\);', 'MODULE_DESCRIPTION("FunctionFS copy accepting vendor class descriptors (Handtop wired controller)");', 1)
VENDOR = ('\t\t} else if (*current_class == USB_CLASS_VENDOR_SPEC) {\n'
          '\t\t\tpr_vdebug("vendor class descriptor\\n");\t/* e.g. Xbox 360 0x21 (17 bytes) */\n'
          '\t\t\tbreak;\n')
sub(r'(\t\t\} else \{\n\t\t\tpr_vdebug\("unknown descriptor: )', lambda m: VENDOR + m.group(1), 1)
open(dst, "w").write("// Generated by Handtop build/06c-ffs-xinput.sh from the kernel's f_fs.c. Do not edit.\n" + s)
PY
cat > "$M/Makefile" <<'MK'
obj-m := usb_f_fs_xinput.o
usb_f_fs_xinput-y := f_fs_xinput.o
ccflags-y += -I$(srctree)/drivers/usb/gadget -I$(srctree)/drivers/usb/gadget/function
MK
make -C "$T" -s M="$M" modules
KO="$M/usb_f_fs_xinput.ko"

# Every symbol version it imports must match the ROCKNIX kernel (as for the decoder module)
[ -f "$K/rocknix.versions" ] || die "$K/rocknix.versions missing: run 06b-cedrus.sh first"
bad=$(/sbin/modprobe --dump-modversions "$KO" | awk 'NR==FNR{r[$2]=$1; next} ($2 in r) && r[$2]!=$1' "$K/rocknix.versions" -)
[ -z "$bad" ] || die "symbol version mismatch against the ROCKNIX kernel:\n$bad"
[ "$(/sbin/modinfo -F vermagic "$KO")" = "$(/sbin/modinfo -F vermagic "$(find "$ROCKNIX_EX/modules/$KVER" -name '*.ko*' | head -1)")" ] \
  || die "vermagic mismatch"

install -D -m644 "$KO" "$ROOTFS/usr/lib/modules/$KVER/extra/usb_f_fs_xinput.ko"
chroot_mount
in_chroot "depmod -a $KVER"
echo "Wired controller FunctionFS module installed ($(/sbin/modinfo -F vermagic "$KO"))."
