#!/usr/bin/env python3
"""List every file in a built root filesystem that no Debian package owns, and sort it into the
classes in classes.txt (which Handtop package ships it, image-only, or generated by Debian's own
scripts). Read-only. Exits 1 if any file is unclassified, so nothing Handtop installs can be
forgotten when the build becomes packages (project doc update-system.md, step 2).

    sudo python3 build/pkg/audit-unowned.py <rootfs> [--list CLASS]
    python3 build/pkg/audit-unowned.py --overlay      (no root needed: every tracked overlay file
                                                      must map to a Handtop package or a diversion)
"""
import fnmatch
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Not walked: kernel/pseudo filesystems, state that is never shipped, and trees handled elsewhere
# (ROCKNIX's modules and firmware: reflash-only; /home and /root: image provisioning).
SKIP = ("/proc", "/sys", "/dev", "/run", "/tmp", "/var/tmp", "/var/lib/dpkg", "/var/lib/apt",
        "/var/cache", "/var/log", "/home", "/root", "/usr/lib/modules", "/usr/lib/firmware",
        "/boot", "/media", "/mnt", "/lost+found", "/var/lib/systemd")
MERGED = {"/bin": "/usr/bin", "/sbin": "/usr/sbin", "/lib": "/usr/lib", "/lib64": "/usr/lib64"}


def canon(p):
    for old, new in MERGED.items():
        if p == old or p.startswith(old + "/"):
            return new + p[len(old):]
    return p


def owned_paths(root, ignore_prefix=None):
    """Paths dpkg owns. ignore_prefix: packages whose files count as not owned (build-debs.py
    passes "handtop-", so a rootfs that already has Handtop's packages is packaged again)."""
    owned = set()
    for lst in glob.glob(os.path.join(root, "var/lib/dpkg/info/*.list")):
        if ignore_prefix and os.path.basename(lst).startswith(ignore_prefix):
            continue
        with open(lst, errors="replace") as f:
            for line in f:
                owned.add(canon(line.rstrip("\n")))
    # files moved aside by dpkg-divert are still Debian's
    div = os.path.join(root, "var/lib/dpkg/diversions")
    if os.path.exists(div):
        lines = open(div).read().split("\n")
        for i in range(0, len(lines) - 2, 3):
            owned.add(canon(lines[i + 1]))
    return owned


def classes():
    rules = []
    with open(os.path.join(HERE, "classes.txt")) as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cls, pat = line.split(None, 1)
            rules.append((cls, pat.strip(), n))
    return rules


def diversions():
    out = {}
    with open(os.path.join(HERE, "diversions.txt")) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if line:
                out[line[1]] = line[0]
    return out


def diversion_owners():
    """{path: the Debian package that owns it} from diversions.txt."""
    out = {}
    with open(os.path.join(HERE, "diversions.txt")) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if line:
                out[line[1]] = line[2]
    return out


def check_overlay():
    import subprocess
    top = os.path.dirname(os.path.dirname(HERE))
    files = subprocess.run(["git", "-C", top, "ls-files", "overlay"], check=True, capture_output=True,
                           text=True, timeout=60).stdout.split()
    rules, div, bad = classes(), diversions(), []
    for f in files:
        p = f[len("overlay"):]
        cls = div.get(p) or next((c for c, pat, _ in rules if fnmatch.fnmatchcase(p, pat)), "UNCLASSIFIED")
        if not cls.startswith("handtop-"):
            bad.append("%s  %s" % (cls, p))
    print("%d overlay files, %d not in a Handtop package" % (len(files), len(bad)))
    for b in bad:
        print("  " + b)
    return 1 if bad else 0


def main():
    if sys.argv[1:] == ["--overlay"]:
        return check_overlay()
    root = sys.argv[1].rstrip("/")
    want = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "--list" else None
    owned = owned_paths(root)
    rules = classes()
    found = {}
    for dp, dns, fns in os.walk(root):
        rel = dp[len(root):] or "/"
        if rel.startswith(SKIP):
            dns[:] = []
            continue
        for name in fns + [d for d in dns if os.path.islink(os.path.join(dp, d))]:
            p = rel.rstrip("/") + "/" + name
            if p in owned or name.endswith(".pyc") or "/__pycache__/" in p + "/":
                continue
            cls = next((c for c, pat, _ in rules if fnmatch.fnmatchcase(p, pat)), "UNCLASSIFIED")
            found.setdefault(cls, []).append(p)
    if want:
        print("\n".join(sorted(found.get(want, []))))
        return 0
    for cls in sorted(found):
        print("%6d  %s" % (len(found[cls]), cls))
    bad = sorted(found.get("UNCLASSIFIED", []))
    for p in bad[:200]:
        print("UNCLASSIFIED", p)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
