"""Render a resolved theme into the files Handtop's components read.

render(theme, state_dir) writes into a fresh folder next to state_dir and swaps it in at the end,
so a component never sees half a theme:

  theme.env          key='value' lines for scripts and apps (handtop_theme.current reads it)
  waybar.css         taskbar (rg35xxh-themed waybar: -s)
  mako.conf          notifications
  labwc/themerc      window title bars (linked as the user's labwc theme "Handtop")
  wlogout.css        power menu
  nwg-drawer.css     app drawer
  foot.ini           terminal
  wallpaper.png      when the theme has an image
  icons/             taskbar, power menu and External Controller images (flat file names)
  icon-theme/        GTK icon theme "Handtop-Current": app icons, Wi-Fi and Bluetooth tray icons

Components never read theme files; only these. Nothing here runs anything: applying (gsettings,
restarts) is the Theme app's job."""
import os
import shutil
import tempfile

from . import colors as C
from . import schema as S

ICON_THEME = "Handtop-Current"
# Bump when the rendered output changes, so --ensure re-renders after an update.
RENDER_VERSION = 4
# Only the id goes into headers: it is [a-z0-9-] (a theme name could close a CSS comment).
HEADER = "Generated by rg35xxh-theme from the theme {id}; edits are overwritten."


def _flat_name(slot):
    group, name = slot.split("/")
    if group == "taskbar" and name in ("apps", "power"):
        return f"panel-{name}.png"
    if group == "power-menu":
        return f"power-{name}.png"
    return f"{name}.png"


def _place(theme, slot, dest, ops):
    """Write the image for slot to dest. Returns False for a "system" slot (nothing written)."""
    how = theme.images[slot]
    if how[0] == "system":
        return False
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    if how[0] == "file":
        shutil.copyfile(how[1], dest)
    else:
        w, h, _k = S.IMAGE_SLOTS[slot]
        if "-shake" in slot:
            ops.shift(how[1], dest, int(slot.rsplit("-shake", 1)[1]))
        else:
            ops.scale(how[1], dest, w, h)
    return True


# ---- configs --------------------------------------------------------------------------------------
def _fs(theme, px):
    return max(1, round(px * theme.fonts["scale"]))


